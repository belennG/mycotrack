"""Record the assistant's answers for the frontend's demo mode.

Run from ``backend/``:

    python -m scripts.record_demo_answers

The demo has no backend, so it cannot call the assistant. Instead of faking answers, this
script runs the *real* assistant, with the real model, on the *exact same sample data* the
demo shows, and saves the results to ``frontend/src/demo/assistantRecordings.json``. The demo
replays them and labels them as recordings.

How the data matches: the demo's sample data is generated by ``frontend/src/demo/demoData.ts``.
This script asks Node to run that very file with the clock fixed at the moment of recording,
and loads the result into an in-memory database. So the values the model saw are the values
a visitor sees (only the dates move with the day they visit).

Needs ``ANTHROPIC_API_KEY`` and Node 22.18 or later (it runs the TypeScript file directly).
Costs a few tenths of a cent. Re-run it when the sample data or the assistant changes.
"""

import json
import os
import shutil
import subprocess  # nosec B404
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

import anthropic
from dotenv import load_dotenv
from sqlalchemy import create_engine, func
from sqlalchemy.orm import Session, sessionmaker
from sqlalchemy.pool import StaticPool

from agent import run_agent
from agent.loop import DEFAULT_MODEL
from auth.tenancy import OrgContext
from database import Base
from models.batch import Batch, BatchStatus
from models.organization import Membership, MemberRole, Organization
from models.tracking import Tracking
from models.user import User
from services.alerts import record_alerts

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "frontend" / "src" / "demo" / "assistantRecordings.json"

# The suggested questions of the demo. Keep them to things the sample data can answer, plus one
# request to write, to show that the assistant is read-only.
QUESTIONS = [
    "Which of my batches need attention?",
    "Why is there an alert on Oyster-Block-01?",
    "How is Oyster-Block-01 doing?",
    "Compare the average temperature of my active batches.",
    "Why did KingOyster-Trial-02 fail?",
    "¿Cómo van mis lotes activos?",
    "Add a reading of 23 °C to Oyster-Block-01.",
]

# Haiku 5.5, USD per million tokens.
PRICE_IN, PRICE_OUT = 0.10, 0.50

DUMP_SEED = """
Date.now = () => Number(process.env.NOW_MS);
const { createSeed } = await import(process.env.SEED_FILE);
console.log(JSON.stringify(createSeed()));
"""


def dump_demo_seed(now: datetime) -> dict:
    """The demo's own sample data, generated by its own code at the given moment."""
    node = shutil.which("node")
    if node is None:
        raise SystemExit(
            "Node 22.18 or later is needed to build the demo's sample data."
        )
    # B404 and B603 do not apply: this is a fixed command. The program is found on PATH,
    # the script is a constant, and the only values passed in (a timestamp and a file path
    # inside this repository) travel as environment variables, never on the command line.
    result = subprocess.run(  # nosec B603
        [node, "--input-type=module", "-e", DUMP_SEED],
        capture_output=True,
        text=True,
        check=True,
        env={
            **os.environ,
            "NOW_MS": str(int(now.timestamp() * 1000)),
            "SEED_FILE": (REPO / "frontend/src/demo/demoData.ts").as_uri(),
        },
    )
    return json.loads(result.stdout)


def naive_utc(iso: str | None) -> datetime | None:
    if iso is None:
        return None
    return datetime.fromisoformat(iso.replace("Z", "+00:00")).replace(tzinfo=None)


def load_into_database(db: Session, seed: dict) -> OrgContext:
    """Put the demo's batches, readings and alerts into the database as one organization's data."""
    user = User(auth0_sub="auth0|demo", email="demo@example.com", name="Demo User")
    org = Organization(name="Demo Farm", slug="demo-farm")
    db.add_all([user, org])
    db.flush()
    membership = Membership(
        user_id=user.id, organization_id=org.id, role=MemberRole.OWNER
    )
    db.add(membership)

    ids: dict[str, uuid.UUID] = {}
    for item in seed["batches"]:
        ids[item["id"]] = uuid.uuid5(uuid.NAMESPACE_URL, item["id"])
        db.add(
            Batch(
                id=ids[item["id"]],
                organization_id=org.id,
                batch_name=item["batch_name"],
                crop_type=item["crop_type"],
                status=BatchStatus(item["status"]),
                start_date=naive_utc(item["start_date"]),
                expected_harvest_date=naive_utc(item["expected_harvest_date"]),
                actual_harvest_date=naive_utc(item.get("actual_harvest_date")),
                location=item["location"],
                notes=item.get("notes"),
            )
        )
    db.flush()
    for item in seed["trackings"]:
        db.add(
            Tracking(
                batch_id=ids[item["batch_id"]],
                tracking_date=naive_utc(item["tracking_date"]),
                temperature=item["temperature"],
                humidity=item["humidity"],
                ph_level=item["ph_level"],
                moisture=item["moisture"],
                notes=item.get("notes"),
            )
        )
    db.flush()

    # The alerts the demo shows: what the rules say about each batch as its readings stand.
    # (The demo works them out with a TypeScript copy of the same rules.)
    for batch in db.query(Batch).filter(Batch.organization_id == org.id):
        latest = (
            db.query(func.max(Tracking.tracking_date))
            .filter(Tracking.batch_id == batch.id)
            .scalar()
        )
        record_alerts(db, batch, now=latest)
    db.commit()
    return OrgContext(user=user, organization=org, membership=membership)


def main() -> int:
    load_dotenv()
    if not os.getenv("ANTHROPIC_API_KEY"):
        print("ANTHROPIC_API_KEY is not set. Put it in backend/.env.")
        return 1

    now = datetime.now(timezone.utc).replace(second=0, microsecond=0)
    seed = dump_demo_seed(now)

    engine = create_engine(
        "sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool
    )
    Base.metadata.create_all(engine)
    db = sessionmaker(bind=engine, expire_on_commit=False)()
    ctx = load_into_database(db, seed)
    print(
        f"Loaded {len(seed['batches'])} batches, {len(seed['trackings'])} readings.\n"
    )

    client = anthropic.Anthropic()
    answers = []
    total_in = total_out = 0
    for question in QUESTIONS:
        result = run_agent(question, ctx, db, client, now=now.replace(tzinfo=None))
        if not result.completed:
            print(f"INCOMPLETE answer for {question!r}; not recording. Re-run.")
            return 1
        total_in += result.input_tokens
        total_out += result.output_tokens
        answers.append(
            {
                "question": question,
                "answer": result.answer,
                "tools": [call.name for call in result.tool_calls],
                "input_tokens": result.input_tokens,
                "output_tokens": result.output_tokens,
            }
        )
        print(f"Q: {question}\n   tools: {[c.name for c in result.tool_calls]}\n")

    OUTPUT.write_text(
        json.dumps(
            {
                "recorded_at": now.isoformat(),
                "model": DEFAULT_MODEL,
                "answers": answers,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    cost = total_in * PRICE_IN / 1e6 + total_out * PRICE_OUT / 1e6
    print(
        f"Wrote {OUTPUT.relative_to(REPO)} ({total_in} tokens in, {total_out} out, ${cost:.4f})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
